#!/usr/bin/env python3
"""Unit tests for stack/generate-compose.py.

The pool is generated, so a mismatch between the generator and the committed
docker-compose.yml is invisible until someone runs the stack and finds a port
that does not match the docs. These cover the two decisions that are easy to get
subtly wrong -- base port and node count -- plus the shape of the output.

Run: python3 -m unittest discover -s tests -v
"""

import importlib.util
import io
import json
import pathlib
import sys
import tempfile
import unittest
from contextlib import redirect_stdout
from unittest import mock

REPO = pathlib.Path(__file__).resolve().parent.parent
STACK = REPO / "stack"

# The module is `generate-compose.py`: a hyphen rules out a plain import, so it
# is loaded from its path. Kept here rather than renamed so the documented
# `python3 stack/generate-compose.py` command keeps working.
_spec = importlib.util.spec_from_file_location("generate_compose", STACK / "generate-compose.py")
gc = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(gc)


class ResolveBasePort(unittest.TestCase):
    """An explicit --base-port must always win."""

    def test_explicit_wins_with_existing_pool(self):
        self.assertEqual(gc.resolve_base_port(19090, ["http://127.0.0.1:18090"]), 19090)

    def test_explicit_wins_with_empty_pool(self):
        # Regression: the old expression read `explicit or parsed if current
        # else 18090`, so an empty pool discarded --base-port without a word.
        self.assertEqual(gc.resolve_base_port(19090, []), 19090)

    def test_falls_back_to_existing_pool(self):
        self.assertEqual(gc.resolve_base_port(None, ["http://127.0.0.1:18090"]), 18090)

    def test_falls_back_to_default_when_nothing_known(self):
        self.assertEqual(gc.resolve_base_port(None, []), 18090)

    def test_rejects_a_port_that_would_overflow(self):
        with self.assertRaises(ValueError):
            gc.resolve_base_port(65535, ["x"] * 6)

    def test_rejects_a_nonsensical_port(self):
        for bad in (0, -1, 70000):
            with self.assertRaises(ValueError):
                gc.resolve_base_port(bad, [])


class ResolveNodeCount(unittest.TestCase):
    def test_explicit_wins(self):
        self.assertEqual(gc.resolve_node_count(10, ["http://127.0.0.1:18090"]), 10)

    def test_keeps_existing_size(self):
        self.assertEqual(gc.resolve_node_count(None, ["x"] * 6), 6)

    def test_defaults_to_three(self):
        self.assertEqual(gc.resolve_node_count(None, []), 3)

    def test_rejects_more_nodes_than_the_alphabet_can_name(self):
        # string.ascii_lowercase is a hard ceiling: compose() would silently
        # drop the services it cannot name.
        with self.assertRaises(ValueError) as ctx:
            gc.resolve_node_count(27, [])
        self.assertIn("ids", str(ctx.exception))

    def test_rejects_a_pool_of_zero(self):
        with self.assertRaises(ValueError):
            gc.resolve_node_count(0, [])


class Proxies(unittest.TestCase):
    def test_contiguous_ports(self):
        self.assertEqual(
            gc.proxies(18090, 3),
            ["http://127.0.0.1:18090", "http://127.0.0.1:18091", "http://127.0.0.1:18092"],
        )

    def test_empty_pool_is_empty(self):
        self.assertEqual(gc.proxies(18090, 0), [])


class ComposeOutput(unittest.TestCase):
    def setUp(self):
        self.text = gc.compose(3, 18090, 86400)

    def test_declares_itself_generated(self):
        # The first line is the only thing stopping a hand edit from silently
        # diverging from the generator.
        self.assertTrue(self.text.startswith("# GENERATED BY stack/generate-compose.py"))

    def test_one_warp_and_one_proxy_per_node(self):
        for node in "abc":
            self.assertIn(f"  alztrk-warp-{node}:", self.text)
            self.assertIn(f"  tinyproxy-{node}:", self.text)
        self.assertNotIn("  alztrk-warp-d:", self.text)

    def test_node_ids_never_exceed_the_alphabet(self):
        # string.ascii_lowercase is the pool's ceiling; a bigger --nodes must
        # fail loudly at generation rather than silently dropping services.
        text = gc.compose(30, 18090, 86400)
        self.assertEqual(text.count("container_name: ofu-warp-"), 26)

    def test_publishes_each_node_on_its_own_port(self):
        for offset, node in enumerate("abc"):
            self.assertIn(f'- "{18090 + offset}:8888"', self.text)

    def test_proxy_shares_the_warp_namespace(self):
        self.assertIn("network_mode: service:alztrk-warp-a", self.text)

    def test_requires_explicit_tos_acceptance(self):
        # Silent acceptance of Cloudflare's terms is the one thing that must
        # never regress.
        self.assertIn("WARP_ACCEPT_TOS=${WARP_ACCEPT_TOS:-0}", self.text)

    def test_dedupe_knows_the_pool(self):
        self.assertIn("POOL_NODES=alztrk-warp-a,alztrk-warp-b,alztrk-warp-c", self.text)

    def test_markers_volume_is_shared_with_the_proxies(self):
        self.assertGreaterEqual(self.text.count("ofu-dedupe:/markers"), 4)

    def test_uses_the_pinned_engine(self):
        self.assertIn(gc.ENGINE_IMAGE, self.text)

    def test_rotation_intervals_are_staggered(self):
        # Lockstep rotation is what made the pool churn: every node re-registered
        # at once and tripped Cloudflare's rate limit.
        self.assertIn("WARP_ROTATION_INTERVAL=86400", self.text)
        self.assertIn("WARP_ROTATION_INTERVAL=86425", self.text)
        self.assertIn("WARP_ROTATION_INTERVAL=86450", self.text)


class EngineWarpCompose(unittest.TestCase):
    """The engine-managed mode keeps only config-init and the engine."""

    def setUp(self):
        self.text = gc.compose_engine_warp()

    def test_declares_itself_generated(self):
        self.assertTrue(self.text.startswith("# GENERATED BY stack/generate-compose.py"))

    def test_has_no_external_pool(self):
        for marker in ("alztrk-warp-", "tinyproxy-", "ofu-dedupe", "ofu-warp-"):
            self.assertNotIn(marker, self.text)

    def test_keeps_config_init_and_engine(self):
        self.assertIn("  config-init:", self.text)
        self.assertIn("  opencode-engine:", self.text)
        self.assertIn(gc.ENGINE_IMAGE, self.text)

    def test_engine_has_host_networking(self):
        # The userspace WARP tunnel needs outbound UDP and source-address
        # binding, both of which require the host namespace.
        self.assertIn("network_mode: host", self.text)

    def test_source_prefix_is_injected_from_the_environment(self):
        self.assertIn("WARP_SOURCE_IPV6=${WARP_SOURCE_IPV6:-}", self.text)
        self.assertIn("source_ipv6", self.text)

    def test_requires_explicit_tos_acceptance(self):
        self.assertIn("WARP_ACCEPT_TOS=${WARP_ACCEPT_TOS:-0}", self.text)
        self.assertIn('if [ "$$WARP_ACCEPT_TOS" != "1" ]', self.text)


class CommittedArtefactsAreInSync(unittest.TestCase):
    """The committed docker-compose.yml must be what the generator produces.

    This is the check that turns "do not hand-edit" from a comment into a
    guarantee.
    """

    def test_docker_compose_matches_generator(self):
        committed = (STACK / "docker-compose.yml").read_text()
        cfg = json.loads((STACK / "config.json").read_text())
        if gc.engine_warp_enabled(cfg):
            self.assertEqual(
                committed,
                gc.compose_engine_warp(),
                "stack/docker-compose.yml is out of sync with the generator; "
                "run python3 stack/generate-compose.py",
            )
            return
        base = gc.resolve_base_port(None, cfg.get("proxies", []))
        count = gc.resolve_node_count(None, cfg.get("proxies", []))
        self.assertEqual(
            committed,
            gc.compose(count, base, 86400),
            "stack/docker-compose.yml is out of sync with the generator; "
            "run python3 stack/generate-compose.py",
        )

    def test_config_proxies_match_the_compose_ports(self):
        cfg = json.loads((STACK / "config.json").read_text())
        if gc.engine_warp_enabled(cfg):
            self.assertEqual(cfg["proxies"], ["direct"])
            return
        self.assertEqual(cfg["proxies"], gc.proxies(gc.resolve_base_port(None, cfg["proxies"]),
                                                     gc.resolve_node_count(None, cfg["proxies"])))


class MainWritesBothArtefacts(unittest.TestCase):
    def test_resizes_and_rewrites_compose_and_config(self):
        with tempfile.TemporaryDirectory() as tmp:
            stack = pathlib.Path(tmp)
            (stack / "config.json").write_text(json.dumps({"proxies": ["http://127.0.0.1:18090"]}))
            argv = ["generate-compose.py", "--nodes", "4", "--base-port", "19090"]
            with mock.patch.object(gc, "STACK", stack), mock.patch.object(sys, "argv", argv):
                with redirect_stdout(io.StringIO()):
                    gc.main()
            cfg = json.loads((stack / "config.json").read_text())
            self.assertEqual(
                cfg["proxies"],
                [f"http://127.0.0.1:{p}" for p in range(19090, 19094)],
            )
            compose = (stack / "docker-compose.yml").read_text()
            self.assertEqual(compose.count("container_name: ofu-warp-"), 4)
            self.assertIn('- "19093:8888"', compose)

    def test_engine_warp_mode_emits_minimal_compose(self):
        with tempfile.TemporaryDirectory() as tmp:
            stack = pathlib.Path(tmp)
            (stack / "config.json").write_text(json.dumps({
                "warp": {"enabled": True},
                "proxies": ["direct"],
            }))
            argv = ["generate-compose.py"]
            with mock.patch.object(gc, "STACK", stack), mock.patch.object(sys, "argv", argv):
                with redirect_stdout(io.StringIO()):
                    gc.main()
            cfg = json.loads((stack / "config.json").read_text())
            self.assertEqual(cfg["proxies"], ["direct"])
            compose = (stack / "docker-compose.yml").read_text()
            self.assertIn("opencode-engine:", compose)
            self.assertNotIn("alztrk-warp-", compose)

    def test_engine_warp_mode_rejects_external_pool_flags(self):
        with tempfile.TemporaryDirectory() as tmp:
            stack = pathlib.Path(tmp)
            (stack / "config.json").write_text(json.dumps({
                "warp": {"enabled": True},
                "proxies": ["direct"],
            }))
            argv = ["generate-compose.py", "--nodes", "4"]
            with mock.patch.object(gc, "STACK", stack), mock.patch.object(sys, "argv", argv):
                with self.assertRaises(SystemExit):
                    gc.main()


if __name__ == "__main__":
    unittest.main()
