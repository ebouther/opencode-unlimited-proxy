#!/usr/bin/env python3
"""Generate stack/docker-compose.yml and the proxy pool in stack/config.json.

Usage:
    python3 stack/generate-compose.py            # keep the current node count
    python3 stack/generate-compose.py --nodes 4  # resize the pool
    python3 stack/generate-compose.py --nodes 6 --base-port 18090 --node-rotation 86400

Each node is:
    alztrk-warp-<id>  Cloudflare WARP tunnel in its own network namespace
    tinyproxy-<id>    CONNECT proxy sharing that namespace, published on the host

Plus one ofu-dedupe service that keeps the egress addresses distinct; see
stack/dedupe.py for why that is not automatic.

After regenerating:  docker compose -f stack/docker-compose.yml up -d --build
"""

from __future__ import annotations

import argparse
import json
import pathlib
import string

STACK = pathlib.Path(__file__).resolve().parent

# The engine implements the four free-tier gates (see docs/free-tier-gates.md).
# Pinned on purpose: upstream broke compatibility twice in one week
# (v1.3.8 session layout, v1.4.0), and `latest` is a liability for a shared repo.
# To upgrade: check https://github.com/jasonxu114514/opencode2api/releases
ENGINE_IMAGE = "ghcr.io/jasonxu114514/opencode2api:v1.4.0"
ENGINE_KEY = "local-test-key"  # dev-only key, override in config.json for real use


def compose(n_nodes: int, base_port: int, node_rotation: int) -> str:
    ids = list(string.ascii_lowercase)[:n_nodes]
    ports = {i: base_port + n for n, i in enumerate(ids)}

    out: list[str] = []
    w = out.append

    w("# GENERATED BY stack/generate-compose.py - do not edit by hand.")
    w("# Each node = one WARP network namespace + one CONNECT proxy on its own port.")
    w("")
    w("x-warp: &warp")
    w("  build:")
    w("    context: ./warp")
    w("    dockerfile: Dockerfile")
    w("  image: ofu-warp-rotator:local")
    w("  privileged: true")
    w("  cap_add:")
    w("    - NET_ADMIN")
    w("  devices:")
    w("    - /dev/net/tun:/dev/net/tun")
    w("  restart: unless-stopped")
    w("")
    w("x-tinyproxy: &tinyproxy")
    w("  build:")
    w("    context: ./tinyproxy")
    w("  image: ofu-tinyproxy:local")
    w("  restart: unless-stopped")
    w("")
    w("services:")
    w("  # Seeds the engine's config into its named volume (bind-mounting that")
    w("  # path breaks startup, so it is copied instead).")
    w("  config-init:")
    w("    image: busybox:1.36")
    w("    command: [\"sh\", \"-c\", \"install -o 1000 -g 1000 -m 0644 /seed.json /vol/config.json\"]")
    w("    volumes:")
    w("      - ./config.json:/seed.json:ro")
    w("      - ofu-engine:/vol")
    w('    restart: "no"')
    w("")

    for n, node in enumerate(ids):
        # Stagger the nodes' own rotation so the pool never rotates in lockstep.
        # The interval is deliberately long: the dedupe service owns rotation in
        # a de-duplicated pool. Leaving it short makes the nodes undo the
        # arbiter's work every couple of minutes, and churn buys nothing when
        # WARP only offers a handful of addresses per region anyway.
        rot = node_rotation + n * 25
        w(f"  alztrk-warp-{node}:")
        w("    <<: *warp")
        w(f"    container_name: ofu-warp-{node}")
        w("    environment:")
        w("      - CORS_ALLOW_ORIGINS=*")
        w(f"      - WARP_ROTATION_INTERVAL={rot}")
        # Cloudflare's terms must be accepted explicitly, never silently.
        w("      - WARP_ACCEPT_TOS=${WARP_ACCEPT_TOS:-0}")
        w("    ports:")
        w(f'      - "{ports[node]}:8888"')
        w("    volumes:")
        w(f"      - ofu-warp-{node}:/app/data")
        w("")
        w(f"  tinyproxy-{node}:")
        w("    <<: *tinyproxy")
        w(f"    container_name: ofu-proxy-{node}")
        w(f"    network_mode: service:alztrk-warp-{node}")
        w("    depends_on:")
        w(f"      - alztrk-warp-{node}")
        w("    environment:")
        w("      # Names this node's drain marker, /markers/<NODE_ID>.")
        w(f"      - NODE_ID={node}")
        w("    volumes:")
        w("      - ofu-dedupe:/markers")
        w("")

    w("  # Keeps egress addresses distinct across the pool. WARP draws from a")
    w("  # small per-region pool, so nodes collide by default; this one polls")
    w("  # every node, re-rolls the collisions, and drains nodes that cannot be")
    w("  # given their own address. Best effort: if it dies, the pool still runs.")
    w("  ofu-dedupe:")
    w("    build:")
    w("      context: ./dedupe")
    w("    image: ofu-dedupe:local")
    w("    container_name: ofu-dedupe")
    w("    command:")
    w("      - \"--interval=${DEDUPE_INTERVAL:-30}\"")
    w("    environment:")
    w(f"      - POOL_NODES={','.join(f'alztrk-warp-{n}' for n in ids)}")
    w("    volumes:")
    w("      - ofu-dedupe:/markers")
    w("    restart: unless-stopped")
    w("")

    w("  opencode-engine:")
    w(f"    image: {ENGINE_IMAGE}")
    w("    container_name: ofu-engine")
    w("    network_mode: host   # so 127.0.0.1:<proxy port> resolves the pool")
    w("    volumes:")
    w("      - ofu-engine:/var/lib/opencode2api")
    w("    restart: unless-stopped")
    w("    depends_on:")
    w("      config-init:")
    w("        condition: service_completed_successfully")
    w("")
    w("volumes:")
    w("  ofu-engine:")
    w("  ofu-dedupe:      # per-node drain markers, shared with the proxies")
    for node in ids:
        w(f"  ofu-warp-{node}:")
    return "\n".join(out) + "\n"


def proxies(base_port: int, n_nodes: int) -> list[str]:
    return [f"http://127.0.0.1:{base_port + n}" for n in range(n_nodes)]


def resolve_base_port(explicit: int | None, current: list[str]) -> int:
    """The port the first proxy node listens on.

    An explicit --base-port always wins, including when config.json has no
    proxies yet. (The previous single-expression version read as
    `explicit or parsed if current else 18090`, because the conditional binds
    looser than `or` -- which silently dropped --base-port on a pool-less
    config instead of honouring it.)
    """
    if explicit is not None:
        if explicit < 1 or explicit > 65535:
            raise ValueError(f"--base-port must be between 1 and 65535, got {explicit}")
        if explicit + resolve_node_count(None, current) - 1 > 65535:
            raise ValueError(f"--base-port {explicit} overflows the port range for this pool size")
        return explicit
    if current:
        return int(current[0].rsplit(":", 1)[1])
    return 18090


def resolve_node_count(explicit: int | None, current: list[str]) -> int:
    """Keep the existing pool size unless told otherwise."""
    if explicit is not None:
        if explicit < 1:
            raise ValueError(f"--nodes must be at least 1, got {explicit}")
        if explicit > len(string.ascii_lowercase):
            raise ValueError(
                f"--nodes {explicit} exceeds the {len(string.ascii_lowercase)} ids this "
                f"generator can name (a-z); a larger pool needs the id scheme extended"
            )
        return explicit
    return len(current) or 6


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--nodes", type=int, default=None)
    ap.add_argument("--base-port", type=int, default=None)
    ap.add_argument(
        "--node-rotation",
        type=int,
        default=86400,
        help=(
            "seconds between a node's own rotations (default: 86400). The dedupe "
            "service rotates on collision, so this only needs to be short enough "
            "to escape an address that stops working on its own."
        ),
    )
    args = ap.parse_args()

    cfg_path = STACK / "config.json"
    cfg = json.loads(cfg_path.read_text())
    current = cfg.get("proxies", [])

    base_port = resolve_base_port(args.base_port, current)
    n_nodes = resolve_node_count(args.nodes, current)

    compose_path = STACK / "docker-compose.yml"
    compose_path.write_text(compose(n_nodes, base_port, args.node_rotation))

    cfg["proxies"] = proxies(base_port, n_nodes)
    cfg_path.write_text(json.dumps(cfg, indent=2) + "\n")

    print(f"docker-compose.yml: {n_nodes} nodes on ports {base_port}-{base_port + n_nodes - 1}")
    print(f"config.json proxies: {cfg['proxies']}")


if __name__ == "__main__":
    main()
